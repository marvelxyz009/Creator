"""Manual Agent Mode for Scene Director — works without an Anthropic API key.

This module implements the two-phase BMAD-style workflow:

    Phase 1 — `prepare_scene_director()`
        Loads inputs, assembles the bundle, loads the prompt template,
        hydrates the user prompt with Jinja2, and writes a copy-paste-ready
        Markdown file. No LLM call.

    Phase 2 — `validate_scene_director_output()`
        Reads a file the human saved containing Claude's response (from the
        Claude extension in VSCode/Cursor, or any LLM chat), extracts the
        YAML block, validates against the scene_blueprint schema, and writes
        the canonical artifact.

The Anthropic-API path in `scene_director_only.py` remains available for
environments that prefer direct API calls. The manual mode is the default
because most contributors use Claude in their IDE, not the raw API.

Reuses (no duplication): BundleAssembler, PromptLoader, render_system_prompt,
render_user_prompt, extract_yaml_from_response, validate_scene_blueprint.
"""

from __future__ import annotations

import logging
import time
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from orchestrator.core.artifact import (
    read_markdown,
    write_markdown,
    write_yaml,
)
from orchestrator.core.bundle import BundleAssembler
from orchestrator.core.config import Config
from orchestrator.prompts.loader import PromptLoader
from orchestrator.prompts.render import (
    extract_yaml_from_response,
    render_system_prompt,
    render_user_prompt,
)
from orchestrator.workflows.scene_director_only import (
    REQUIRED_SCENE_BLUEPRINT_FIELDS,
    validate_scene_blueprint,
)

logger = logging.getLogger("orchestrator.scene_director_manual")


# ─── Result types ─────────────────────────────────────────────────────────────

@dataclass
class PrepareResult:
    """Outcome of `prepare-agent scene-director`."""

    status: str   # "ok" | "hard_reject"
    prompt_path: Path | None = None
    manual_dir: Path | None = None
    expected_output_path: Path | None = None
    system_chars: int = 0
    user_chars: int = 0
    duration_seconds: float = 0.0
    notes: str = ""

    @property
    def ok(self) -> bool:
        return self.status == "ok"


@dataclass
class ValidateResult:
    """Outcome of `validate-agent-output scene-director`."""

    status: str   # "ok" | "hard_reject"
    output: dict[str, Any] | None = None
    artifact_path: Path | None = None
    input_path: Path | None = None
    validation_violations: list[str] = field(default_factory=list)
    agent_status: str | None = None
    duration_seconds: float = 0.0
    notes: str = ""

    @property
    def ok(self) -> bool:
        return self.status == "ok"


# ─── Structured logging helper ────────────────────────────────────────────────

def _log_step(step: str, **fields_kv: Any) -> None:
    if fields_kv:
        kvs = " ".join(f"{k}={v}" for k, v in fields_kv.items())
        logger.info("step=%s %s", step, kvs)
    else:
        logger.info("step=%s", step)


# ─── Manual-prompt file template ──────────────────────────────────────────────

_MANUAL_PROMPT_HEADER = """\
# Scene Director — Manual Prompt

> Generated by `python -m orchestrator prepare-agent scene-director --sample {sample}`
> Generated at: {timestamp}
> Mode: **Manual Agent Mode** (no Anthropic API call from the orchestrator)

## For the human operator

1. Open Claude (the extension in VSCode/Cursor, the web app, or any LLM chat).
2. Paste **everything below the `--- BEGIN PROMPT ---` line** into a new
   conversation. The orchestrator has hydrated the template with your sample's
   inputs already — no further editing is needed.
3. Ask Claude to follow the instructions. Wait for the response.
4. Save Claude's response (the YAML block, ideally the entire response) to:
   ```
   {expected_output_path}
   ```
   `.yaml` and `.md` are both accepted — the validator extracts the YAML block.
5. Run:
   ```
   python -m orchestrator validate-agent-output scene-director \\
     --sample {sample} \\
     --input {expected_output_path}
   ```
6. On success, the canonical artifact lands at
   `{canonical_artifact_path}` and can be committed (if desired) or compared
   against the golden in `samples/{sample}/outputs/`.

If validation fails the orchestrator prints a structured list of violations.
Edit Claude's output (or re-prompt Claude with the diagnostics) and re-run
`validate-agent-output` until it passes.

--- BEGIN PROMPT ---

# AGENT ROLE — System Prompt

The block below is the Scene Director's full agent contract. Treat it as your
identity, responsibilities, output format, validation checklist, and
anti-patterns. Honor it.

{system_prompt}

---

# TASK — User Prompt

{user_prompt}

---

# Required output

Emit a **single YAML document** wrapped in a fenced ```` ```yaml ... ``` ````
block. Include **all 10 required `scene_blueprint` fields**:

{required_fields_list}

Do not write any prose before or after the fenced block. Do not include any
explanation. Output the YAML and nothing else.
"""


def _build_manual_prompt(
    *,
    sample_name: str,
    system_prompt: str,
    user_prompt: str,
    expected_output_path: Path,
    canonical_artifact_path: Path,
    repo_root: Path,
) -> str:
    """Assemble the human-readable manual prompt file."""
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    fields_md = "\n".join(f"  - `{name}`" for name in REQUIRED_SCENE_BLUEPRINT_FIELDS)

    def _rel(p: Path) -> str:
        try:
            return str(p.relative_to(repo_root)).replace("\\", "/")
        except ValueError:
            return str(p)

    return _MANUAL_PROMPT_HEADER.format(
        sample=sample_name,
        timestamp=timestamp,
        expected_output_path=_rel(expected_output_path),
        canonical_artifact_path=_rel(canonical_artifact_path),
        system_prompt=system_prompt.strip(),
        user_prompt=user_prompt.strip(),
        required_fields_list=fields_md,
    )


# ─── Phase 1: prepare-agent ──────────────────────────────────────────────────

def prepare_scene_director(sample_dir: Path, config: Config) -> PrepareResult:
    """Build the manual prompt file. No LLM call. Reproducible from inputs."""
    t0 = time.time()
    sample_dir = sample_dir.resolve()

    if not (sample_dir / "inputs").exists():
        raise FileNotFoundError(
            f"Sample is missing inputs/: {sample_dir}. "
            f"Run `python -m orchestrator inspect-sample --sample {sample_dir}`."
        )

    manual_dir = sample_dir / "generated" / "manual"
    manual_dir.mkdir(parents=True, exist_ok=True)
    prompt_path = manual_dir / "scene-director-prompt.md"
    expected_output_path = manual_dir / "scene-director-output.yaml"
    canonical_artifact_path = sample_dir / "generated" / "01-scene-blueprint.yaml"

    # Assemble bundle from sample inputs (same path as the API mode).
    assembler = BundleAssembler(sample_dir=sample_dir)
    bundle = assembler.assemble_for_scene_director(task_id="scene:01")
    _log_step(
        "bundle_loaded",
        sample=sample_dir.name,
        pinned_artifacts=len(bundle.pinned_artifacts),
        rules=len(bundle.constraints.get("rules", [])),
    )

    # Load + hydrate.
    loader = PromptLoader(prompts_dir=config.prompts_dir)
    template = loader.load("scene-director")
    system_prompt = render_system_prompt(template.system_prompt_markdown)
    user_prompt = render_user_prompt(bundle)
    _log_step(
        "prompt_hydrated",
        template=str(template.path.relative_to(config.repo_root)),
        system_chars=len(system_prompt),
        user_chars=len(user_prompt),
    )

    # Build the manual prompt and write to disk.
    content = _build_manual_prompt(
        sample_name=sample_dir.name,
        system_prompt=system_prompt,
        user_prompt=user_prompt,
        expected_output_path=expected_output_path,
        canonical_artifact_path=canonical_artifact_path,
        repo_root=config.repo_root,
    )
    write_markdown(prompt_path, content)
    _log_step(
        "manual_prompt_written",
        path=str(prompt_path.relative_to(config.repo_root)),
        size_chars=len(content),
    )

    return PrepareResult(
        status="ok",
        prompt_path=prompt_path,
        manual_dir=manual_dir,
        expected_output_path=expected_output_path,
        system_chars=len(system_prompt),
        user_chars=len(user_prompt),
        duration_seconds=time.time() - t0,
        notes="manual prompt ready; paste into Claude, save response, then run validate-agent-output",
    )


# ─── Phase 2: validate-agent-output ──────────────────────────────────────────

def validate_scene_director_output(
    sample_dir: Path,
    input_path: Path,
    config: Config,
) -> ValidateResult:
    """Read the human-saved LLM output, extract YAML, validate, write canon."""
    t0 = time.time()
    sample_dir = sample_dir.resolve()
    input_path = input_path.resolve()

    result = ValidateResult(status="hard_reject", input_path=input_path)

    if not input_path.exists():
        result.notes = f"input file not found: {input_path}"
        result.duration_seconds = time.time() - t0
        return result

    raw_text = read_markdown(input_path)
    if not raw_text.strip():
        result.notes = f"input file is empty: {input_path}"
        result.duration_seconds = time.time() - t0
        return result

    _log_step("output_loaded", path=str(input_path), size_chars=len(raw_text))

    parsed = extract_yaml_from_response(raw_text)
    if parsed is None:
        result.notes = (
            "could not extract YAML from input. Expected either a ```yaml ... ``` "
            "fenced block or a pure YAML document. Edit the input file or re-prompt "
            "Claude with: 'Output the YAML wrapped in a single ```yaml ... ``` fenced block.'"
        )
        result.duration_seconds = time.time() - t0
        _log_step("yaml_extracted", success=False)
        return result

    _log_step(
        "yaml_extracted",
        success=True,
        top_level_keys=list(parsed.keys()),
    )

    result.output = parsed
    result.agent_status = parsed.get("status")

    violations = validate_scene_blueprint(parsed)
    result.validation_violations = violations
    _log_step("schema_validated", violations=len(violations))

    if violations:
        result.notes = (
            f"schema validation failed: {len(violations)} violation(s). "
            f"See result.validation_violations."
        )
        result.duration_seconds = time.time() - t0
        return result

    artifact_path = sample_dir / "generated" / "01-scene-blueprint.yaml"
    write_yaml(artifact_path, parsed)
    result.artifact_path = artifact_path
    _log_step("artifact_written", path=str(artifact_path.relative_to(config.repo_root)))

    result.status = "ok"
    result.duration_seconds = time.time() - t0
    result.notes = "output validated and canonical artifact written"
    return result


# ─── Pretty-printers ──────────────────────────────────────────────────────────

def print_prepare_summary(result: PrepareResult, repo_root: Path) -> None:
    icon = "✓" if result.ok else "✗"
    print(f"{icon} prepare-agent scene-director")
    print(f"  status              : {result.status}")
    print(f"  system prompt chars : {result.system_chars}")
    print(f"  user prompt chars   : {result.user_chars}")
    print(f"  duration            : {result.duration_seconds:.2f}s")
    if result.prompt_path:
        try:
            rel = result.prompt_path.relative_to(repo_root)
        except ValueError:
            rel = result.prompt_path
        print(f"  manual prompt       : {rel}")
    if result.expected_output_path:
        try:
            rel = result.expected_output_path.relative_to(repo_root)
        except ValueError:
            rel = result.expected_output_path
        print(f"  save Claude reply to: {rel}")
    print()
    print("Next steps:")
    print("  1. Open the manual prompt above and copy the section under '--- BEGIN PROMPT ---'")
    print("  2. Paste into Claude extension in VSCode/Cursor (or any LLM chat)")
    print("  3. Save Claude's response to the path above")
    print("  4. python -m orchestrator validate-agent-output scene-director \\")
    print("       --sample <sample> --input <path-from-step-3>")
    if result.notes:
        print(f"\n  notes               : {result.notes}")


def print_validate_summary(result: ValidateResult, repo_root: Path) -> None:
    icon = "✓" if result.ok else "✗"
    print(f"{icon} validate-agent-output scene-director")
    print(f"  status              : {result.status}")
    if result.agent_status:
        print(f"  agent self-status   : {result.agent_status}")
    print(f"  duration            : {result.duration_seconds:.2f}s")
    if result.input_path:
        try:
            rel = result.input_path.relative_to(repo_root)
        except ValueError:
            rel = result.input_path
        print(f"  input               : {rel}")
    if result.validation_violations:
        print(f"  validation violations: {len(result.validation_violations)}")
        for v in result.validation_violations:
            print(f"    - {v}")
    if result.artifact_path:
        try:
            rel = result.artifact_path.relative_to(repo_root)
        except ValueError:
            rel = result.artifact_path
        print(f"  canonical artifact  : {rel}")
    if result.notes:
        print(f"  notes               : {result.notes}")
